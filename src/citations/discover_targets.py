class TargetDiscoverer:
    """Manages the discovery, querying, and filtering of the 30 citation targets."""

    @staticmethod
    def get_all_targets() -> List[Dict[str, Any]]:
        return CITATION_TARGETS_RAW

    @staticmethod
    def get_target_by_id(target_id: str) -> Dict[str, Any]:
        for t in CITATION_TARGETS_RAW:
            if t["target_id"].upper() == target_id.upper():
                return t
        raise KeyError(f"Target ID {target_id} not found in CITATION_TARGETS_RAW")

    @staticmethod
    def filter_by_priority(priority: str) -> List[Dict[str, Any]]:
        return [t for t in CITATION_TARGETS_RAW if t["priority"].lower() == priority.lower()]

    @staticmethod
    def filter_by_page_type(page_type: str) -> List[Dict[str, Any]]:
        return [t for t in CITATION_TARGETS_RAW if page_type.lower() in t["page_type"].lower()]


